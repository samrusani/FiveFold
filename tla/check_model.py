"""Regenerate the G2 contract tables and check the gateway model with TLC (0021)."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

from fivefold.domain.contracts import Contract
from fivefold.gateway import state_machine as machine

HERE = Path(__file__).resolve().parent
JAR = HERE.parent / ".tla/tla2tools.jar"
TABLES = HERE / "GatewayTables.tla"
PROFILES = {"ci": (1, "1g"), "nightly": (2, "2g")}


def _literal(value: object) -> str:
    return json.dumps("none" if value is None else str(value))


def _tuple(*items: object) -> str:
    return "<<" + ", ".join(_literal(item) for item in items) + ">>"


def render_tables() -> bytes:
    lines = ["---- MODULE GatewayTables ----", "\\* Generated by tla/check_model.py."]
    for contract in Contract:
        edges = []
        for row in machine.TRANSITIONS:
            for reason in sorted(row.reasons):
                try:
                    edge = machine.check_transition(row.source, row.target, reason, contract)
                except machine.IllegalTransition:
                    continue
                if edge != row:
                    raise ValueError("TRANSITIONS and check_transition disagree")
                edges.append(_tuple(edge.tid, edge.source, edge.target, reason))
        lines.append(f"Edges{contract} == {{" + ",\n ".join(edges) + "}")
    lines.append("LegalEdges(c) == CASE " + " [] ".join(f'c = "{c}" -> Edges{c}' for c in Contract))
    grants = [
        _tuple(source, target)
        for source, targets in machine.GRANT_TRANSITIONS.items()
        for target in sorted(targets)
    ]
    lines.append("GrantEdges == {" + ",\n ".join(grants) + "}")
    checks = []
    for contract in Contract:
        for attempt in (1, 2):
            try:
                kind = machine.required_check(contract, attempt)
            except machine.GatewayRuleError:
                continue
            checks.append(f'<<"{contract}", {attempt}, "{kind}">>')
    lines.append("SendChecks == {" + ",\n ".join(checks) + "}")
    return ("\n".join([*lines, "===="]) + "\n").encode("utf-8")


def check_tables(path: Path) -> bytes:
    generated = render_tables()
    if path.read_bytes() != generated:
        raise ValueError("GatewayTables.tla differs from Python. Regenerate with make tla-tables.")
    return generated


def run_tlc(profile: str) -> None:
    subprocess.run([sys.executable, HERE.parent / "scripts/tla_tools.py", "check"], check=True)
    generated = check_tables(TABLES)
    workers, heap = PROFILES[profile]
    with TemporaryDirectory(prefix="fivefold-tlc-") as directory:
        work = Path(directory)
        (work / TABLES.name).write_bytes(generated)
        shutil.copyfile(HERE / "Gateway.tla", work / "Gateway.tla")
        config = f"{profile}.cfg"
        shutil.copyfile(HERE / config, work / config)
        subprocess.run(
            [
                "java",
                "-XX:+UseParallelGC",
                f"-Xmx{heap}",
                "-Djava.rmi.server.hostname=127.0.0.1",
                "-jar",
                str(JAR),
                "-workers",
                str(workers),
                "-fp",
                "0",
                "-metadir",
                "states",
                "-config",
                config,
                "Gateway.tla",
            ],
            cwd=work,
            check=True,
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("tables", *PROFILES))
    action = parser.parse_args().action
    try:
        if action == "tables":
            TABLES.write_bytes(render_tables())
        else:
            run_tlc(action)
    except subprocess.CalledProcessError as error:
        raise SystemExit(error.returncode) from None
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from None


if __name__ == "__main__":
    main()
